@configclass
class IsaaclabDreamwaqSceneCfg(InteractiveSceneCfg):
    """DreamWaQ locomotion scene."""

    # ------------------------------------------------------------------
    # Terrain  Generates flat, rough, stairs, and obstacle terrains later.
    # ------------------------------------------------------------------
    terrain = TerrainImporterCfg(
        prim_path="/World/ground",
        terrain_type="generator",
        terrain_generator=ROUGH_TERRAINS_CFG,
        max_init_terrain_level=0,
        collision_group=-1,
        physics_material=sim_utils.RigidBodyMaterialCfg(
            friction_combine_mode="multiply",
            restitution_combine_mode="multiply",
            static_friction=1.0,
            dynamic_friction=1.0,
        ),
        visual_material=sim_utils.MdlFileCfg(
            mdl_path=f"{ISAACLAB_NUCLEUS_DIR}/Materials/TilesMarbleSpiderWhiteBrickBondHoned/TilesMarbleSpiderWhiteBrickBondHoned.mdl",
            project_uvw=True,
            texture_scale=(0.25, 0.25),
        ),
        debug_vis=False,
    )

    # ------------------------------------------------------------------
    # Robot -- Replaces the CartPole robot with the quadruped.
    # ------------------------------------------------------------------
    robot: ArticulationCfg = UNITREE_GO2_CFG.replace(
        prim_path="{ENV_REGEX_NS}/Robot"
    )

    # ------------------------------------------------------------------
    # Height Scanner --Provides a height scanner. The critic can use terrain information during training.
    # ------------------------------------------------------------------
    height_scanner = RayCasterCfg(
        prim_path="{ENV_REGEX_NS}/Robot/base",
        offset=RayCasterCfg.OffsetCfg(pos=(0.0, 0.0, 20.0)),
        ray_alignment="yaw",
        pattern_cfg=patterns.GridPatternCfg(
            resolution=0.1,
            size=[1.6, 1.0],
        ),
        debug_vis=False,
        mesh_prim_paths=["/World/ground"],
    )

    # ------------------------------------------------------------------
    # Contact Sensor  Detects foot-ground contact, needed for rewards and terminations.
    # ------------------------------------------------------------------
    contact_forces = ContactSensorCfg(
        prim_path="{ENV_REGEX_NS}/Robot/.*",
        history_length=3,
        track_air_time=True,
        debug_vis=False,
        force_threshold=1.0,
    )

    # ------------------------------------------------------------------
    # Light  Lights the environment.
    # ------------------------------------------------------------------
    sky_light = AssetBaseCfg(
        prim_path="/World/skyLight",
        spawn=sim_utils.DomeLightCfg(
            intensity=750.0,
            texture_file=f"{ISAAC_NUCLEUS_DIR}/Materials/Textures/Skies/PolyHaven/kloofendal_43d_clear_puresky_4k.hdr",
        ),
    )

