@configclass
class ObservationsCfg:
    """Observation specifications for DreamWaQ."""

    @configclass
    class PolicyCfg(ObsGroup):
        """Observations used by the policy network."""

        proprioception = ObsTerm(
            func=mdp.CustomProprioceptiveObservations,
            params={
                "asset_cfg": SceneEntityCfg("robot"),
                "sensor_cfg": SceneEntityCfg("contact_forces"),
            },
        )

        history = ObsTerm(
            func=mdp.CustomProprioceptionHistory,
            params={
                "asset_cfg": SceneEntityCfg("robot"),
                "sensor_cfg": SceneEntityCfg("contact_forces"),
                "num_hist": 5,
            },
        )

        def __post_init__(self):
            self.enable_corruption = False
            self.concatenate_terms = True

    @configclass
    class CriticCfg(ObsGroup):
        """Privileged observations used during training."""

        privileged = ObsTerm(
            func=mdp.CustomPrivilegedObservations,
            params={
                "asset_cfg": SceneEntityCfg("robot"),
                "sensor_cfg": SceneEntityCfg("contact_forces"),
            },
        )

        def __post_init__(self):
            self.enable_corruption = False
            self.concatenate_terms = True

    policy: PolicyCfg = PolicyCfg()
    critic: CriticCfg = CriticCfg()

